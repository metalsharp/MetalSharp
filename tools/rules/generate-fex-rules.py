#!/usr/bin/env python3
"""Generate `configs/mtsp-rules-fex.toml`, the Arm64 FEX build's rule set, from the regular build's.

The regular x86_64 build reads `configs/mtsp-rules.toml` (its backend compiles the same rules into
`app/src-c/runtime/mtsp_catalog.c`). The FEX build runs on MetalSharp Wine, whose lanes are Mullion
(`dxmt`, `dxmt_32`), VKD3D-Proton (`vkd3d`), DXVK (`dxvk`, which also takes the D3D9 route), OpenGL
(`wine_bare`) and the x86 Mono/FNA lane (`fna_x86`). Each regular rule is translated the way the FEX
backend translated it at launch before the FEX build had a rule set of its own
(`ms_mtsp_default_rules_json`, `canonical_mtsp_pipeline` and `ms_wine_route_pipeline`), starting from
the pipeline the regular backend actually uses (its compiled catalog), so a game's default lane does
not change. Then the per-game choices verified on MetalSharp Wine (FEX_VERIFIED) apply.

    python3 tools/rules/generate-fex-rules.py           # rewrite configs/mtsp-rules-fex.toml
    python3 tools/rules/generate-fex-rules.py --check   # fail when it is out of date
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGULAR = ROOT / "configs" / "mtsp-rules.toml"
FEX = ROOT / "configs" / "mtsp-rules-fex.toml"
CATALOG = ROOT / "app" / "src-c" / "runtime" / "mtsp_catalog.c"
VERSION = "1.0.0"

# The regular backend's own ids, normalized as ms_mtsp_default_rules_json does.
REGULAR_ALIASES = {
    "m11": "dxmt",
    "m10": "dxmt",
    "m11_32": "dxmt_32",
    "m10_32": "dxmt_32",
    "m9": "d3d9",
    "dxvk": "d3d9",
    "dxvk_32": "d3d9",
    "d3d9_32": "d3d9",
    "auto": "vkd3d",
}

# The FEX lane each regular pipeline ran on (app/src-c/runtime/wine_runtime.c ms_wine_route_pipeline):
# D3DMetal and GPTK are Apple's x86_64 runtimes, so their D3D12 games take VKD3D-Proton; DXVK takes the
# D3D9 route; FNA games on arm64 Mono run as Windows programs on Mullion.
FEX_LANES = {
    "dxmt": "dxmt",
    "dxmt_32": "dxmt_32",
    "vkd3d": "vkd3d",
    "d3dmetal": "vkd3d",
    "m13": "vkd3d",
    "d3d9": "dxvk",
    "fna_arm64": "dxmt",
    "fna_x86": "fna_x86",
    "wine_bare": "wine_bare",
}

# Per-game lanes verified on MetalSharp Wine: appid -> (lane, name, note).
FEX_VERIFIED = {
    2054970: ("dxmt", "Dragon's Dogma 2", "runs on Mullion"),
    1174180: ("dxmt", "Red Dead Redemption 2", "runs best on Mullion"),
    2322010: ("dxmt", "God of War Ragnarök", "runs on Mullion and VKD3D-Proton"),
    3527290: ("vkd3d", "PEAK", "runs on VKD3D-Proton and Mullion"),
}

HEADER = f"""# MTSP Pipeline Override Rules: the Arm64 FEX build (MetalSharp {VERSION} and later on MetalSharp Wine)
# appid -> pipeline_id mapping. The regular x86_64 build's rules are configs/mtsp-rules.toml.
#
# Generated by tools/rules/generate-fex-rules.py from the regular rules; edit the regular rules or
# the generator's FEX_VERIFIED choices, then run it again (CI checks that this file is current).
#
# Lanes on MetalSharp Wine:
# - dxmt/dxmt_32: Mullion, D3D10/D3D11/D3D12 to Metal (64-bit/i386).
# - vkd3d: VKD3D-Proton, D3D12 on Vulkan through MoltenVK (the regular build's D3DMetal and GPTK titles).
# - dxvk: DXVK, D3D9/D3D10/D3D11 on Vulkan through MoltenVK (the regular build's D3D9 route).
# - wine_bare: Wine's own Direct3D over WineMetalGL (OpenGL), and Vulkan-native titles.
# - fna_x86: x86 XNA/FNA/Mono titles.
#
# Verified on MetalSharp Wine:
"""

RULE_SET = """
[rule_set]
build = "fex"
version = "{version}"
schema = 1
"""


def catalog_pipelines() -> dict[int, str]:
    """The pipeline the regular backend uses per appid: its compiled catalog's default_pipeline."""
    text = CATALOG.read_text()
    joined = "".join(re.findall(r'^    "(.*)",?$', text, re.M))
    data = json.loads(joined.encode().decode("unicode_escape"))
    return {int(rule["appid"]): rule["default_pipeline"] for rule in data["rules"]}


def fex_lane(regular: str) -> str:
    regular = REGULAR_ALIASES.get(regular, regular)
    return FEX_LANES.get(regular, regular)


def generate() -> str:
    regular_text = REGULAR.read_text()
    catalog = catalog_pipelines()
    section = re.compile(r"^\[overrides\.(\d+)\]\s*$")
    pipeline_line = re.compile(r'^pipeline = "([^"]+)"\s*$')
    out: list[str] = []
    header = HEADER + "".join(
        f"# - {appid} {name}: {note}.\n" for appid, (_, name, note) in sorted(FEX_VERIFIED.items())
    )
    out.append(header.rstrip("\n"))
    out.append(RULE_SET.format(version=VERSION).rstrip("\n"))
    seen: set[int] = set()
    appid = None
    started = False
    for line in regular_text.splitlines():
        match = section.match(line)
        if match:
            started = True
            appid = int(match.group(1))
            seen.add(appid)
            out.append("")
            out.append(line)
            continue
        if not started:
            continue
        match = pipeline_line.match(line)
        if match and appid is not None:
            if appid in FEX_VERIFIED:
                lane = FEX_VERIFIED[appid][0]
            else:
                lane = fex_lane(catalog.get(appid, match.group(1)))
            out.append(f'pipeline = "{lane}"')
            appid = None
            continue
        if line.strip() or (out and out[-1].strip()):
            out.append(line)
    for appid, (lane, name, _) in sorted(FEX_VERIFIED.items()):
        if appid not in seen:
            out += ["", f"[overrides.{appid}]", f'pipeline = "{lane}"', f'name = "{name}"']
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.rstrip("\n") + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv[1:]:
        if not FEX.exists() or FEX.read_text() != text:
            print(
                "configs/mtsp-rules-fex.toml is out of date; run python3 tools/rules/generate-fex-rules.py",
                file=sys.stderr,
            )
            return 1
        print("configs/mtsp-rules-fex.toml is current")
        return 0
    FEX.write_text(text)
    print(f"wrote {FEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
